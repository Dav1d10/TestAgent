"""
Runs LLM-generated code and tests inside an isolated Docker container.

The LLM output is untrusted and must never execute directly on the agent's host.
Each run gets a fresh, ephemeral container that is destroyed on exit.

Security constraints applied at runtime:
- No network access (--network none)
- Memory cap: 256 MB
- CPU cap: 0.5 cores
- Hard timeout: 30 s (container is killed if exceeded)
- Read-only volume mount: the host filesystem cannot be modified
"""

import subprocess
import tempfile
import os
import uuid
from dataclasses import dataclass
from enum import Enum


SANDBOX_IMAGE = "test-agent-sandbox:latest"
DEFAULT_TIMEOUT_SECONDS = 30
SANDBOX_STARTED_MARKER = "__TEST_AGENT_SANDBOX_STARTED__"


class SandboxOutcome(str, Enum):
    """Structured outcome of one isolated pytest execution."""

    PASSED = "passed"
    TEST_FAILED = "test_failed"
    TIMED_OUT = "timed_out"
    INFRASTRUCTURE_ERROR = "infrastructure_error"


@dataclass
class SandboxResult:
    outcome: SandboxOutcome
    stdout: str
    stderr: str
    exit_code: int

    @property
    def passed(self) -> bool:
        return self.outcome == SandboxOutcome.PASSED

    @property
    def timed_out(self) -> bool:
        return self.outcome == SandboxOutcome.TIMED_OUT


def _strip_startup_marker(stdout: str) -> tuple[bool, str]:
    """Return whether the container started and remove its internal marker."""
    lines = stdout.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if line.rstrip("\r\n") == SANDBOX_STARTED_MARKER:
            return True, "".join(lines[:index] + lines[index + 1 :])
    return False, stdout


def build_sandbox_image(sandbox_dir: str) -> None:
    """
    Builds the sandbox Docker image.
    Only needs to run once, or when sandbox/requirements.txt changes.
    """
    result = subprocess.run(
        ["docker", "build", "-t", SANDBOX_IMAGE, sandbox_dir],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"Failed to build sandbox image:\n{result.stderr}")


def run_test_in_sandbox(
    source_code: str,
    test_code: str,
    module_name: str = "target_module",
    timeout_seconds: int = DEFAULT_TIMEOUT_SECONDS,
) -> SandboxResult:
    """
    Runs a generated test against source code inside an isolated container.

    Args:
        source_code: the original function/module being tested.
        test_code: the pytest test generated by the LLM (must import module_name).
        module_name: the filename stem given to the source code file.
        timeout_seconds: hard kill limit before the container is stopped.

    Returns:
        SandboxResult with a structured outcome plus stdout, stderr, and exit code.
    """
    run_id = uuid.uuid4().hex[:8]

    with tempfile.TemporaryDirectory(prefix=f"sandbox_{run_id}_") as tmp_dir:
        source_path = os.path.join(tmp_dir, f"{module_name}.py")
        test_path = os.path.join(tmp_dir, f"test_{module_name}.py")

        with open(source_path, "w") as f:
            f.write(source_code)
        with open(test_path, "w") as f:
            f.write(test_code)

        # Normalize to forward slashes for Docker Desktop on Windows
        mount_path = tmp_dir.replace("\\", "/")
        container_name = f"sandbox-run-{run_id}"

        cmd = [
            "docker", "run",
            "--rm",
            "--name", container_name,
            "--network", "none",
            "--memory", "256m",
            "--cpus", "0.5",
            "-v", f"{mount_path}:/sandbox/work:ro",
            "-w", "/sandbox/work",
            SANDBOX_IMAGE,
            "sh", "-c",
            f'printf "{SANDBOX_STARTED_MARKER}\\n"; '
            'exec pytest --tb=short -v -p no:cacheprovider "$1"',
            "test-agent-runner",
            f"test_{module_name}.py",
        ]

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=timeout_seconds,
            )
            container_started, stdout = _strip_startup_marker(result.stdout)
            if not container_started or result.returncode not in range(0, 6):
                outcome = SandboxOutcome.INFRASTRUCTURE_ERROR
            elif result.returncode == 0:
                outcome = SandboxOutcome.PASSED
            else:
                outcome = SandboxOutcome.TEST_FAILED
            return SandboxResult(
                outcome=outcome,
                stdout=stdout,
                stderr=result.stderr,
                exit_code=result.returncode,
            )
        except subprocess.TimeoutExpired:
            try:
                subprocess.run(["docker", "kill", container_name], capture_output=True)
            except OSError:
                # The timeout classification remains valid even if the runtime
                # disappears before the best-effort container cleanup.
                pass
            return SandboxResult(
                outcome=SandboxOutcome.TIMED_OUT,
                stdout="",
                stderr=f"Execution cancelled: exceeded the {timeout_seconds}s limit",
                exit_code=-1,
            )
        except OSError as exc:
            return SandboxResult(
                outcome=SandboxOutcome.INFRASTRUCTURE_ERROR,
                stdout="",
                stderr=f"Sandbox runtime could not be started: {exc}",
                exit_code=-1,
            )
